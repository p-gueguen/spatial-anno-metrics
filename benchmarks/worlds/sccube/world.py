"""The scCube world: realistic expression and tissue geometry behind the same contract as ``sim.py``.

Reads the cache ``generate.py`` built (scCube is not needed here). A section = six tiles, one per sample, each
its own scCube spatial pattern; the cells are scCube VAE cells generated from Yerly et al. 2022 BCC scRNA-seq,
on the 306 genes of the 10x Xenium human breast panel present in that data, with counts drawn at Xenium depth.
``reference`` returns real held-out Yerly cells (never seen by the VAE).

Patterns (``PATTERN`` / ``SAM_SCCUBE_PATTERN`` / ``pattern=``): ``stripes`` (scCube custom stripes, the toy
geometry), ``domains`` (Gaussian random field, delta 25: few large graded domains), ``fine`` (delta 6: many
small patches), ``mixed`` (delta 25 with 30 % of labels permuted, scCube's lamda = 0.7).

Every keyword of ``sim.simulate`` is honoured, so all 15 sweep scenarios run:
- ``weights``: only the vectors ``generate.py`` pre-built (the default and ``rare_type``'s levels); others raise.
- ``n_cells``: 2400 (all weights) and 600 (default weights, edge cases).
- ``n_samples``: 6 only (the tiles).
- ``infiltrate``: a fraction of T_CD8 cells swap positions with random non-T_CD8 cells anywhere in the section:
  scCube's lamda label permutation, restricted to T_CD8 (scCube's own per-type switch ``spatial_cell_type``
  cannot do this: with one type left out it permutes T_CD8 among T_CD8 positions, a no-op).
- ``coexpr``: Myeloid rates gain ``coexpr`` x the mean Fibro rate on Fibro's markers; the reference gets the
  same share of its Fibro cells' counts.
- ``extra_bg``: the first ``extra_bg`` of 960 real genes with the lowest between-type F statistic (generated by
  the same VAE), counted on top of the base panel from their own random stream.
Negative controls: scCube has none. 20 ``NegCtrl*`` features are Poisson at the Xenium breast section's
control-to-gene count ratio (0.0017 x a cell's mean count per panel gene).
"""
from __future__ import annotations

import json
import os
import sys
from functools import lru_cache
from pathlib import Path

import anndata as ad
import numpy as np
import pandas as pd
import scipy.sparse as sp

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "synthetic"))
import sim  # noqa: E402

CACHE = Path(os.environ.get("SAM_SCCUBE_CACHE", Path(__file__).resolve().parent / "cache"))
PATTERNS = ["stripes", "domains", "fine", "mixed"]
PATTERN = os.environ.get("SAM_SCCUBE_PATTERN", "domains")
TYPES = list(sim.TYPES)


@lru_cache(maxsize=1)
def meta() -> dict:
    return json.loads((CACHE / "meta.json").read_text())


def marker_sets(per_type: int = 4) -> dict[str, list[str]]:
    return {t: list(g) for t, g in meta()["marker_sets"].items()}


def t_lineage() -> list[str]:
    return list(meta()["t_lineage"])


def wkey(w) -> str:
    w = np.asarray(w, float)
    return "w" + "-".join(str(int(round(1e4 * x))) for x in w / w.sum())


@lru_cache(maxsize=8)
def _pool(seed: int):
    p = ad.read_h5ad(CACHE / f"pool_s{seed}.h5ad")
    return p.obs["cell_type"].astype(str).to_numpy(), np.asarray(p.X, dtype=np.float64), list(p.var_names)


@lru_cache(maxsize=64)
def _layout(pattern: str, seed: int, n_cells: int, key: str) -> pd.DataFrame:
    f = CACHE / "layouts" / pattern / f"s{seed}_n{n_cells}_{key}.csv.gz"
    if not f.exists():
        have = sorted(p.name for p in (CACHE / "layouts" / pattern).glob(f"s{seed}_*"))
        raise ValueError(f"scCube world: no cached layout for pattern={pattern!r}, seed={seed}, n_cells={n_cells}, "
                         f"weights={key}; generate.py built: {have}")
    return pd.read_csv(f)


@lru_cache(maxsize=1)
def _ref_pool():
    r = ad.read_h5ad(CACHE / "ref_pool.h5ad")
    return r.obs["cell_type"].astype(str).to_numpy(), sp.csr_matrix(r.X), list(r.var_names)


def _fibro_cols(names):
    col = {g: i for i, g in enumerate(names)}
    return [col[g] for g in meta()["marker_sets"]["Fibro"]]


def simulate(seed: int = 0, n_cells: int = 2400, weights=None, n_samples: int = 6, infiltrate: float = 0.0,
             extra_bg: int = 0, coexpr: float = 0.0, pattern: str | None = None, **kw) -> ad.AnnData:
    if kw:
        raise TypeError(f"scCube world: unsupported keyword(s) {sorted(kw)}")
    if n_samples != 6:
        raise ValueError("scCube world: n_samples is fixed at 6 (one scCube tile per sample)")
    m = meta()
    if extra_bg > len(m["extra"]):
        raise ValueError(f"scCube world: extra_bg <= {len(m['extra'])}")
    pattern = pattern or PATTERN
    w = np.asarray(sim.WEIGHTS if weights is None else weights, float)
    lay = _layout(pattern, int(seed), int(n_cells), wkey(w))
    types = lay["cell_type"].to_numpy(str)
    xy = lay[["x", "y"]].to_numpy(float).copy()
    tile = lay["tile"].to_numpy(int).copy()
    n = len(types)
    pt, R, _ = _pool(int(seed))
    idx = np.empty(n, int)
    for t in TYPES:                                   # the first k pool cells of each type
        pos, cand = np.flatnonzero(types == t), np.flatnonzero(pt == t)
        if len(cand) < len(pos):
            raise ValueError(f"scCube world: pool has {len(cand)} {t} cells, layout needs {len(pos)}")
        idx[pos] = cand[: len(pos)]
    npan = len(m["panel"])
    base = R[idx, :npan].copy()
    extra = R[idx, npan:npan + int(extra_bg)]
    if coexpr:
        fc = _fibro_cols(m["panel"])
        base[np.ix_(types == "Myeloid", fc)] += coexpr * R[pt == "Fibro"][:, fc].mean(0)
    if infiltrate:
        ri = np.random.default_rng(seed + 7)
        cd8 = np.flatnonzero(types == "T_CD8")
        move = ri.choice(cd8, int(round(infiltrate * len(cd8))), replace=False)
        partner = ri.choice(np.flatnonzero(types != "T_CD8"), len(move), replace=False)
        xy[move], xy[partner] = xy[partner].copy(), xy[move].copy()
        tile[move], tile[partner] = tile[partner].copy(), tile[move].copy()
    rng_c = np.random.default_rng(seed + 13)
    size = m["scale"] * rng_c.lognormal(0, m["size_sd"], n)
    lam = base * size[:, None]
    Xb = rng_c.poisson(lam)                            # base panel first: same draws whatever the panel size
    Xc = rng_c.poisson(np.repeat((m["ctrl_ratio"] * lam.mean(1))[:, None], m["n_ctrl"], 1))
    Xe = rng_c.poisson(extra * size[:, None])
    X = np.hstack([Xb, Xe, Xc]).astype("float32")
    genes = m["panel"] + m["extra"][: int(extra_bg)] + [f"NegCtrl{i}" for i in range(m["n_ctrl"])]
    lib = np.log1p(Xb.sum(1))
    z = (lib - lib.mean()) / max(lib.std(), 1e-9)
    ar = m["area"]
    eps = np.random.default_rng(seed + 17).standard_normal(n)
    area = ar["median"] * np.exp(ar["sdlog"] * (ar["r_lib"] * z + np.sqrt(1 - ar["r_lib"] ** 2) * eps))
    obs = pd.DataFrame({"truth": types, "label": types, "sample": [f"s{i}" for i in tile], "cell_area": area},
                       index=[f"c{i}" for i in range(n)])
    var = pd.DataFrame({"control": [g.startswith("NegCtrl") for g in genes]}, index=genes)
    a = ad.AnnData(X=sp.csr_matrix(X), obs=obs, var=var)
    a.layers["counts"] = a.X.copy()
    a.obsm["spatial"] = xy
    a.uns["marker_sets"] = marker_sets()
    a.uns["hierarchy"] = dict(sim.HIERARCHY)
    a.uns["world"] = {"seed": seed, "coexpr": coexpr, "extra_bg": extra_bg, "pattern": pattern, "source": "sccube"}
    return sim.finish(a, seed)


def reference(seed: int = 0, n_per_type: int = 300, depth: float | None = None, coexpr: float = 0.0,
              extra_bg: int = 0) -> ad.AnnData:
    """Real held-out Yerly cells (the VAE never saw them): up to ``n_per_type`` per type, real UMI counts on the
    panel (+ ``extra_bg`` extra genes), no controls. ``depth`` thins to that median panel depth (downward only).
    Note: the reference half holds 274 B-lineage cells, so ``n_per_type`` > 274 gives fewer B, and two calls with
    different seeds share cells."""
    m = meta()
    rt, RX, _ = _ref_pool()
    rng = np.random.default_rng(50_000 + seed)
    idx = np.concatenate([rng.choice(np.flatnonzero(rt == t), min(n_per_type, int((rt == t).sum())), replace=False)
                          for t in TYPES])
    npan = len(m["panel"])
    X = np.asarray(RX[idx][:, : npan + int(extra_bg)].todense(), dtype=np.float64)
    types = rt[idx]
    if coexpr:
        fc = _fibro_cols(m["panel"])
        lib = X[:, :npan].sum(1)
        P = RX[np.flatnonzero(rt == "Fibro")][:, :npan]
        prof = np.asarray((P[:, fc].sum(0))).ravel() / max(P.sum(), 1)
        my = types == "Myeloid"
        X[np.ix_(my, fc)] += rng.poisson(coexpr * np.outer(lib[my], prof))
    if depth is not None:
        lib = X[:, :npan].sum(1)
        X = rng.binomial(X.astype(int), min(1.0, depth / max(np.median(lib), 1))).astype(float)
    genes = m["panel"] + m["extra"][: int(extra_bg)]
    a = ad.AnnData(X=sp.csr_matrix(X.astype("float32")),
                   obs=pd.DataFrame({"cell_type": types}, index=[f"r{i}" for i in range(len(types))]),
                   var=pd.DataFrame(index=genes))
    a.layers["counts"] = a.X.copy()
    return a
